-- ============================================================
-- 71. FINANCEIRO DA EQUIPE (LUCRO E DIVISÃO)
-- ============================================================
-- Tela Admin → Financeiro (php/admin/admin_financeiro.php), só para os
-- superadmins (SUPERADMIN_EMAILS no Render). Ver docs/interno/financeiro.md.
--   idpg_valor_liquido_centavos  o que sobra da cobrança depois da taxa do
--                      Asaas (campo netValue). NULL = cobrança anterior a
--                      esta seção: a tela conta o bruto até o botão
--                      "Buscar taxas no Asaas" preencher.
-- id_financeiro_lancamento: o que não passa pelo Asaas, lançado à mão.
--   idfl_tipo          custo   = despesa da equipe (Render, Supabase...);
--                      receita = entrada fora do app (ajuda, doação...);
--                      repasse = dinheiro que saiu para a igreja (parte
--                                dela no lucro) ou para um projeto de missão
--   idfl_destino       só no repasse: igreja | missao
--   idmp_id            só no repasse de missão (opcional): o projeto
-- Idempotente: pode rodar de novo sem erro.

ALTER TABLE "id_pagamento" ADD COLUMN IF NOT EXISTS "idpg_valor_liquido_centavos" INTEGER;

CREATE TABLE IF NOT EXISTS "id_financeiro_lancamento" (
    "idfl_id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "idfl_tipo" VARCHAR(10) NOT NULL,
    "idfl_destino" VARCHAR(10),
    "idmp_id" BIGINT,
    "idfl_categoria" VARCHAR(40) NOT NULL,
    "idfl_descricao" VARCHAR(200),
    "idfl_valor_centavos" INTEGER NOT NULL,
    "idfl_data" DATE NOT NULL,
    "idfl_criado_por" BIGINT,
    "idfl_criado_em" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT "ck_id_financeiro_lancamento_tipo"
        CHECK ("idfl_tipo" IN ('custo', 'receita', 'repasse')),
    CONSTRAINT "ck_id_financeiro_lancamento_destino"
        CHECK (("idfl_tipo" = 'repasse' AND "idfl_destino" IN ('igreja', 'missao'))
            OR ("idfl_tipo" <> 'repasse' AND "idfl_destino" IS NULL)),
    CONSTRAINT "ck_id_financeiro_lancamento_valor"
        CHECK ("idfl_valor_centavos" > 0)
);

CREATE INDEX IF NOT EXISTS "ix_id_financeiro_lancamento_data" ON "id_financeiro_lancamento" ("idfl_data");

ALTER TABLE "id_financeiro_lancamento" ENABLE ROW LEVEL SECURITY;


-- ============================================================
-- 72. CONTRIBUIÇÃO EM MISSÕES (T32)
-- ============================================================
-- O admin cadastra os projetos (php/admin/admin_missoes.php); o fiel vê,
-- contribui com o valor que quiser por Pix ou cartão na página do Asaas e
-- aparece no quadro de apoiadores (php/fiel/missoes.php e missao.php).
-- id_missao_projeto:
--   idmp_status        rascunho (só o admin vê) | ativo | encerrado. Um
--                      projeto ativo com idmp_data_fim no passado é tratado
--                      como encerrado (sem rotina agendada).
--   idmp_meta_centavos meta da barra de progresso (NULL = sem meta)
--   idmp_mostrar_valores  1 = o quadro de apoiadores mostra o valor de
--                      cada contribuição; 0 = só nome e mensagem
-- id_missao_contribuicao:
--   idmc_origem        app (pago pelo Asaas) | manual (oferta recebida
--                      fora do app, lançada pelo superadmin)
--   idmc_recebido_por  equipe | igreja: quem ficou com o dinheiro. Só o que
--                      a equipe recebeu entra no Financeiro; tudo entra na
--                      barra do projeto.
--   idmc_status        status do Asaas (PENDING, RECEIVED, CONFIRMED,
--                      OVERDUE, REFUNDED...); manual = RECEIVED_IN_CASH
--   idmc_pago_em       DATE (dia do pagamento), não TIMESTAMPTZ: o Asaas
--                      manda só a data, e um TIMESTAMPTZ à meia-noite UTC
--                      cairia no dia anterior no horário de Brasília.
--   idf_id             ON DELETE SET NULL: a conta apagada some do quadro,
--                      mas o valor continua no histórico financeiro.
-- Idempotente: pode rodar de novo sem erro.

CREATE TABLE IF NOT EXISTS "id_missao_projeto" (
    "idmp_id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "idmp_titulo" VARCHAR(120) NOT NULL,
    "idmp_local" VARCHAR(100),
    "idmp_descricao" TEXT NOT NULL DEFAULT '',
    "idmp_capa_url" TEXT,
    "idmp_meta_centavos" INTEGER,
    "idmp_data_fim" DATE,
    "idmp_status" VARCHAR(10) NOT NULL DEFAULT 'rascunho',
    "idmp_mostrar_valores" SMALLINT NOT NULL DEFAULT 0,
    "idmp_criado_por" BIGINT,
    "idmp_criado_em" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "idmp_atualizado_em" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT "ck_id_missao_projeto_status"
        CHECK ("idmp_status" IN ('rascunho', 'ativo', 'encerrado')),
    CONSTRAINT "ck_id_missao_projeto_meta"
        CHECK ("idmp_meta_centavos" IS NULL OR "idmp_meta_centavos" > 0)
);

CREATE TABLE IF NOT EXISTS "id_missao_contribuicao" (
    "idmc_id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "idmp_id" BIGINT NOT NULL,
    "idf_id" BIGINT,
    "idmc_origem" VARCHAR(10) NOT NULL DEFAULT 'app',
    "idmc_recebido_por" VARCHAR(10) NOT NULL DEFAULT 'equipe',
    "idmc_nome_exibicao" VARCHAR(100),
    "idmc_anonimo" SMALLINT NOT NULL DEFAULT 0,
    "idmc_mensagem" VARCHAR(280),
    "idmc_valor_centavos" INTEGER NOT NULL,
    "idmc_valor_liquido_centavos" INTEGER,
    "idmc_forma" VARCHAR(20),
    "idmc_status" VARCHAR(30) NOT NULL DEFAULT 'PENDING',
    "idmc_asaas_customer_id" VARCHAR(50),
    "idmc_asaas_payment_id" VARCHAR(50) UNIQUE,
    "idmc_invoice_url" TEXT,
    "idmc_pago_em" DATE,
    "idmc_lancado_por" BIGINT,
    "idmc_criado_em" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "idmc_atualizado_em" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT "ck_id_missao_contribuicao_origem"
        CHECK ("idmc_origem" IN ('app', 'manual')),
    CONSTRAINT "ck_id_missao_contribuicao_recebido"
        CHECK ("idmc_recebido_por" IN ('equipe', 'igreja')),
    CONSTRAINT "ck_id_missao_contribuicao_valor"
        CHECK ("idmc_valor_centavos" > 0),

    CONSTRAINT "fk_id_missao_contribuicao_projeto"
        FOREIGN KEY ("idmp_id")
        REFERENCES "id_missao_projeto" ("idmp_id")
        ON DELETE RESTRICT,

    CONSTRAINT "fk_id_missao_contribuicao_fiel"
        FOREIGN KEY ("idf_id")
        REFERENCES "id_fiel" ("idf_id")
        ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS "ix_id_missao_contribuicao_projeto" ON "id_missao_contribuicao" ("idmp_id", "idmc_status");
CREATE INDEX IF NOT EXISTS "ix_id_missao_contribuicao_fiel" ON "id_missao_contribuicao" ("idf_id", "idmc_criado_em" DESC);
CREATE INDEX IF NOT EXISTS "ix_id_missao_contribuicao_pago" ON "id_missao_contribuicao" ("idmc_pago_em");

ALTER TABLE "id_missao_projeto" ENABLE ROW LEVEL SECURITY;
ALTER TABLE "id_missao_contribuicao" ENABLE ROW LEVEL SECURITY;


-- ============================================================
-- 73. GRUPOS DE PERMISSÕES DOS ADMINS
-- ============================================================
-- Admin → Permissões (php/admin/admin_gerenciar_permissoes.php): cada
-- grupo lista as telas do painel que os admins dele podem abrir; cada
-- admin fica num grupo ou com "acesso total".
--   idag_telas          chaves das telas separadas por vírgula (as de
--                       admin_telas() em php/conexao.php, ex.:
--                       "cursos,conteudos,transmissao"). O Dashboard e as
--                       notificações valem para todos; o Financeiro, só
--                       para superadmin (SUPERADMIN_EMAILS).
--   ida_grupo_id        NULL = acesso total (como era antes desta seção,
--                       então nenhum admin atual perde acesso). Grupo com
--                       admins não pode ser excluído (RESTRICT): excluir
--                       daria acesso total a eles.
-- Idempotente: pode rodar de novo sem erro.

CREATE TABLE IF NOT EXISTS "id_admin_grupo" (
    "idag_id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "idag_nome" VARCHAR(60) NOT NULL,
    "idag_descricao" VARCHAR(200),
    "idag_telas" TEXT NOT NULL DEFAULT '',
    "idag_criado_em" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS "ux_id_admin_grupo_nome" ON "id_admin_grupo" (LOWER("idag_nome"));

ALTER TABLE "id_admin" ADD COLUMN IF NOT EXISTS "ida_grupo_id" BIGINT;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_id_admin_grupo') THEN
        ALTER TABLE "id_admin" ADD CONSTRAINT "fk_id_admin_grupo"
            FOREIGN KEY ("ida_grupo_id") REFERENCES "id_admin_grupo" ("idag_id") ON DELETE RESTRICT;
    END IF;
END $$;

ALTER TABLE "id_admin_grupo" ENABLE ROW LEVEL SECURITY;


