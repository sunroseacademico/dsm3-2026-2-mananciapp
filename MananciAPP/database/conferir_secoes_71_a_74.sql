-- 74. TIPOS DE FIEL (O QUE CADA UM PODE EDITAR)
-- ============================================================
-- Admin → Tipos de fiel (php/admin/admin_tipos_fiel.php): cada tipo lista
-- o que o fiel pode mudar no próprio perfil (php/fiel/perfil.php).
--   idft_permissoes     chaves separadas por vírgula (as de
--                       fiel_permissoes_catalogo() em php/conexao.php):
--                       nome, email, cpf, dados, foto, membro
--   idft_padrao         1 = tipo de quem não tem tipo escolhido (só um).
--   idf_tipo_id         NULL = tipo padrão. ON DELETE SET NULL: excluir um
--                       tipo devolve os fiéis dele ao padrão.
-- Os dois tipos iniciais: "Fiel" (padrão; o que o perfil já permitia:
-- dados pessoais, foto e vínculo de membro) e "Fiel com edição completa"
-- (também nome, e-mail e CPF). Sem esta seção o perfil continua como
-- antes.
-- Idempotente: pode rodar de novo sem erro.

CREATE TABLE IF NOT EXISTS "id_fiel_tipo" (
    "idft_id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "idft_nome" VARCHAR(60) NOT NULL,
    "idft_descricao" VARCHAR(200),
    "idft_permissoes" TEXT NOT NULL DEFAULT '',
    "idft_padrao" SMALLINT NOT NULL DEFAULT 0,
    "idft_criado_em" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS "ux_id_fiel_tipo_nome" ON "id_fiel_tipo" (LOWER("idft_nome"));
CREATE UNIQUE INDEX IF NOT EXISTS "ux_id_fiel_tipo_padrao" ON "id_fiel_tipo" ("idft_padrao") WHERE "idft_padrao" = 1;

