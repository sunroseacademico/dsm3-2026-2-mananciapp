-- ============================================================
-- Banco SIMPLES da plataforma MananciAPP (Missão Evangélica Manancial)
-- Compatível com MySQL 8.0.16+ (testado também no MariaDB 10.4 do XAMPP).
-- ============================================================
-- Retrato do banco em 15/10/2026: as 49 tabelas do app, traduzidas
-- do PostgreSQL (Supabase) que roda em produção. O app usa o Postgres
-- (database/bancosupabase.md); este arquivo é a versão MySQL para estudo
-- e documentação, gerada a partir da estrutura real do banco.
--
-- SIMPLES: as mesmas tabelas e colunas, só com chave primária, chaves
-- estrangeiras básicas e valores padrão. Sem UNIQUE, CHECK, índices
-- extras nem regras de exclusão em cascata (essas regras ficam a
-- cargo do código). Ver "Banco Igreja Robusto.sql" para a versão completa.
--
-- Arquivos (vídeos e capas) NÃO ficam no banco: ficam no Cloudflare R2, e
-- o banco guarda só o caminho com prefixo "r2:" (ex.: IDCT_URL =
-- 'r2:aulas/123_culto.mp4'). Fotos de perfil ficam em ID_FIEL_FOTO.
--
-- CUIDADO: o DROP abaixo apaga e recria o banco "igreja_cursos" do zero.

SET NAMES utf8mb4;
SET FOREIGN_KEY_CHECKS = 0;

DROP DATABASE IF EXISTS igreja_cursos;
CREATE DATABASE igreja_cursos
    CHARACTER SET utf8mb4
    COLLATE utf8mb4_unicode_ci;

USE igreja_cursos;

